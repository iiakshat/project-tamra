"""Write config/actors.json from the strips in assets/chars/<actor>/<anim>.png.

For every animation it records frame size, foot anchor, and per frame:
  tip   - the weapon tip (the forward-most opaque pixel in the upper 80%), relative to
          the anchor, for strike glints and arrow origins;
  waist - uv.y where breathing stops (half the body height), and chest_x.
Display scales live here too, so tuning sizes needs no code.
"""
import json
import pathlib

import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
CHARS = ROOT / "assets" / "chars"

# Game-world scale for each actor's strips (standing height in px ~ strip height x scale).
SCALE = {"hero": 0.52, "soldier": 0.5, "archer": 0.5, "brute": 0.5}
FPS = {"run": 14.0, "jump": 0.0, "strike": 0.0, "cast": 0.0, "death": 3.0}


def main() -> None:
    out = {"_about": "Generated by tools/actors_manifest.py from assets/chars. Edit SCALE/FPS there, not here."}
    for actor_dir in sorted(p for p in CHARS.iterdir() if p.is_dir()):
        anims = {}
        for meta_path in sorted(actor_dir.glob("*.json")):
            meta = json.loads(meta_path.read_text())
            img = np.array(Image.open(meta_path.with_suffix(".png")).convert("RGBA"))
            fw, fh, n = meta["frame_w"], meta["frame_h"], meta["frames"]
            ax, ay = meta["anchor_x"], meta["anchor_y"]
            tips, waists = [], []
            for i in range(n):
                a = img[:, i * fw:(i + 1) * fw, 3] > 60
                ys, xs = np.nonzero(a)
                top, bot = ys.min(), ys.max()
                upper = a[: top + int((bot - top) * 0.8)]
                uy, ux = np.nonzero(upper)
                j = int(np.argmax(ux))
                tips.append([int(ux[j] - ax), int(uy[j] - ay)])
                waists.append(round((top + (bot - top) * 0.5) / fh, 3))
            anims[meta_path.stem] = {
                "frames": n, "frame_w": fw, "frame_h": fh, "anchor": [ax, ay],
                "fps": FPS.get(meta_path.stem, 0.0), "tips": tips, "waist": waists[0],
                "chest_x": round(ax / fw, 3),
            }
        out[actor_dir.name] = {"scale": SCALE.get(actor_dir.name, 0.5), "anims": anims}
    (ROOT / "config" / "actors.json").write_text(json.dumps(out, indent=1))
    print("actors:", ", ".join(k for k in out if not k.startswith("_")))


if __name__ == "__main__":
    main()
